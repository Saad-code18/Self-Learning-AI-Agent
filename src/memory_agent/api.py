"""
api.py - a small HTTP API around the agent (this is what runs inside Docker).

Start it locally with:
    uvicorn memory_agent.api:app --reload --app-dir src
or via Docker:
    docker compose --profile app up --build

Endpoints:
    GET  /health                    -> is Qdrant reachable?
    POST /chat                      -> {"user_id": "alice", "session_id": "s1", "message": "hi"}
    GET  /memories/{user_id}        -> list all memories of a user
    DELETE /memories/{user_id}      -> forget a user
    GET  /stats                     -> token / cost counters since start
    Docs: open http://localhost:8000/docs in a browser (Swagger UI, generated by FastAPI).
"""

from __future__ import annotations

from contextlib import asynccontextmanager
from typing import Optional

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

from memory_agent.agent import MemoryAgent, SessionState
from memory_agent.settings import configure_logging, get_settings

# ---------------------------------------------------------------------------
# Request / response models (FastAPI validates JSON bodies with these)
# ---------------------------------------------------------------------------
class ChatRequest(BaseModel):
    message: str = Field(..., min_length=1, description="What the user says")
    user_id: Optional[str] = Field(None, description="Who is talking (memories are per user)")
    session_id: str = Field("default", description="Chat window id; new id = new session, memories stay")


class MemoryEventOut(BaseModel):
    event: str
    text: str
    memory_id: Optional[str] = None
    old_text: Optional[str] = None


class ChatResponse(BaseModel):
    reply: str
    user_id: str
    session_id: str
    recalled_memories: list[str]
    memory_events: list[MemoryEventOut]
    prompt_tokens: int
    completion_tokens: int
    answer_seconds: float


class MemoryOut(BaseModel):
    id: str
    text: str
    created_at: Optional[str] = None
    updated_at: Optional[str] = None


# ---------------------------------------------------------------------------
# App setup: create ONE agent when the server starts, close it on shutdown
# ---------------------------------------------------------------------------
@asynccontextmanager
async def lifespan(app: FastAPI):
    settings = get_settings()
    settings.validate()
    configure_logging(settings)
    app.state.settings = settings
    app.state.agent = MemoryAgent(settings)
    app.state.sessions = {}  # (user_id, session_id) -> SessionState  (in-memory, fine for a demo)
    yield
    app.state.agent.close()


app = FastAPI(title="Self-Learning Memory Agent", version="1.0.0", lifespan=lifespan)


def _session(user_id: str, session_id: str) -> SessionState:
    """Return the existing session for (user, session_id) or start a new one."""
    key = (user_id, session_id)
    if key not in app.state.sessions:
        app.state.sessions[key] = app.state.agent.start_session(user_id)
    return app.state.sessions[key]


@app.get("/health")
def health():
    ok = app.state.agent.store.ping()
    if not ok:
        raise HTTPException(status_code=503, detail="Qdrant is not reachable")
    return {"status": "ok", "memories_total": app.state.agent.store.count()}


@app.post("/chat", response_model=ChatResponse)
def chat(req: ChatRequest):
    user_id = req.user_id or app.state.settings.default_user_id
    session = _session(user_id, req.session_id)
    result = app.state.agent.chat(session, req.message)
    events = result.learn.events if result.learn else []
    return ChatResponse(
        reply=result.reply,
        user_id=user_id,
        session_id=req.session_id,
        recalled_memories=[m.text for m in result.recalled],
        memory_events=[MemoryEventOut(event=e.event, text=e.text, memory_id=e.memory_id, old_text=e.old_text) for e in events],
        prompt_tokens=result.prompt_tokens,
        completion_tokens=result.completion_tokens,
        answer_seconds=round(result.answer_seconds, 3),
    )


@app.get("/memories/{user_id}", response_model=list[MemoryOut])
def list_memories(user_id: str):
    return [MemoryOut(id=m.id, text=m.text, created_at=m.created_at, updated_at=m.updated_at)
            for m in app.state.agent.list_memories(user_id)]


@app.delete("/memories/{user_id}")
def forget(user_id: str):
    app.state.agent.wait_for_learning()
    app.state.agent.forget_user(user_id)
    # Drop the user's open sessions too, so the next message starts fresh.
    for key in [k for k in app.state.sessions if k[0] == user_id]:
        del app.state.sessions[key]
    return {"status": "deleted", "user_id": user_id}


@app.get("/stats")
def stats():
    return app.state.agent.tracker.summary()
